// Pure helpers for duplicating a promotion (no React, no DB) so they can be unit-tested.

// n-th candidate code for a duplicate: CODE-COPY, CODE-COPY-2, CODE-COPY-3, …
// An existing "-COPY[-N]" suffix is stripped first so copies of copies don't pile up suffixes.
export function promotionCopyCode(code, n) {
  const root = String(code || "").toUpperCase().trim().replace(/-COPY(-\d+)?$/, "");
  const base = `${root}-COPY`;
  return n <= 1 ? base : `${base}-${n}`;
}

// "Summer Sale" -> "Summer Sale (Copy)"; an existing "(Copy)" is not repeated.
export function promotionCopyTitle(title) {
  const t = String(title || "Untitled promotion").trim();
  return /\(Copy\)$/.test(t) ? t : `${t} (Copy)`;
}

/**
 * Builds the data for a new promotion copied from `source` (a plain object).
 * Server-owned fields (_id, timestamps, analytics, usage counters, Stripe linkage) are
 * dropped so the copy starts clean; it is always a Draft. `code` is set by the caller
 * (a unique "-COPY" code), or left out for automatic promotions.
 */
export function buildPromotionCopy(source, code) {
  const {
    _id, id, __v, status, createdAt, updatedAt, analytics,
    stripeCouponId, stripePromotionCodeId, stripeSyncStatus, stripeSyncError, stripeSyncKey,
    code: _oldCode, usageLimits, ...rest
  } = source || {};
  const copy = {
    ...rest,
    title: promotionCopyTitle(source?.title),
    adminStatus: "Draft",
    usageLimits: {
      maxTotalUses: usageLimits?.maxTotalUses ?? null,
      // null means "unlimited per customer", so only a missing value falls back to the default.
      maxUsesPerCustomer: usageLimits && usageLimits.maxUsesPerCustomer !== undefined ? usageLimits.maxUsesPerCustomer : 1,
      currentTotalUses: 0,
    },
  };
  // Sub-document ids (actions, tiers, bundle items) are regenerated by Mongoose.
  if (Array.isArray(copy.actions)) copy.actions = stripIds(copy.actions);
  if (code) copy.code = code;
  return copy;
}

function stripIds(value) {
  if (Array.isArray(value)) return value.map(stripIds);
  if (value && typeof value === "object" && !(value instanceof Date)) {
    const out = {};
    for (const [k, v] of Object.entries(value)) {
      if (k !== "_id") out[k] = stripIds(v);
    }
    return out;
  }
  return value;
}
